export async function execute(interaction, env) {
  // 列出實際註冊的指令，避免日後新增指令卻忘了更新這份說明
  const all = commandNames.map((n) => `\`/${n}\``).join('　');

  return reply(
    {
      embeds: [
        {
          title: '賭圖小蒜頭 使用說明',
          description: '人設提示詞的共用資料庫。以下指令都在這個群組內有效。',
          color: 0x5865f2,
          fields: [...SECTIONS, { name: '所有指令', value: all }],
          footer: { text: '看不到某個指令代表你沒有使用權限' },
        },
      ],
    },
    { ephemeral: true },
  );
}
