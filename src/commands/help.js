// 指令清單由 commands/index.js 在建好之後注入。
//
// 不直接 import 那份清單是因為 index.js 本身會 import 這個檔案，
// 形成循環相依 —— 實測會讓 index.js 在本檔的 data 還在暫時性死區時就去讀它，
// 能不能跑取決於誰先被載入，太脆弱。
let commandNames = [];

export function setCommandNames(names) {
  commandNames = names;
}

